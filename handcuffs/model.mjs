const SNAP = [3.57, 3.16, 3.07, 3.09, 3.10, 2.86, 2.71, 2.73, 2.74, 2.39, 0];
const lerpTable = (tab, x0, dx, x) => { const i = (x - x0) / dx; if (i <= 0) return tab[0]; if (i >= tab.length - 1) return tab[tab.length - 1]; const k = Math.floor(i); return tab[k] + (tab[k + 1] - tab[k]) * (i - k); };

export function alphaJaw(theta) {            // lift the strand's teeth force on the pawl
  if (theta < THETA1 - PITCH || theta >= thetaOf(NPOS)) return 0;
  if (theta < THETA1) { const f = (theta - (THETA1 - PITCH)) / PITCH; return f >= 0.97 ? LEADIN[19] * (1 - f) / 0.03 : lerpTable(LEADIN, 0, 0.05, f); }
  const n = notchAt(theta), f = (theta - thetaOf(n)) / PITCH, tab = n === 1 ? CLICK1 : CLICK;
  if (f < 0.945) return lerpTable(tab, 0, 0.05, f) * (f > 0.9 ? 1 + (f - 0.9) / 0.045 * (tab[19] / lerpTable(tab, 0, 0.05, 0.945) - 1) : 1);
  return lerpTable(SNAP, 0.945, 0.0055, f) * tab[19] / 3.57;
}
export const alphaKey = kappa => kappa > -46 ? 0 : lerpTable(KEY2, -46, -1, kappa) + (kappa < -87 ? 0.11 * (-87 - kappa) : 0);
// + past KEY1's last sample (194: 0.02) the fold lands on the OFF stop at 194.4 (u 0; truth §5)
export const uLimitTurn1 = kappa => kappa < 116 ? 4 : kappa > 194 ? Math.max(0, 0.02 * (194.4 - kappa) / 0.4) : lerpTable(KEY1, 116, 2, kappa);
export const alphaLimit = u => lerpTable(ALIM, 4, -0.25, u);
export const notchAt = theta => theta < THETA1 ? 0 : Math.min(NPOS, 1 + Math.floor((theta - THETA1) / PITCH + 1e-9));

// inside perimeter / width / equivalent diameter of the loop at jaw angle theta (exact for the patent shape)
export function loopAt(theta) {
  const r = 24.8, Rc = 32.7, R0 = 57.5, D = Math.PI / 180;
  const del = 29 - theta, s = Math.sin(Math.abs(del) / 2 * D);
  const per = del >= 0 ? 2 * r * (Math.PI + Math.asin(Rc * s / r) - del / 2 * D) + R0 * del * D : 4 * r * Math.acos(Rc * s / r);
  return { perimeter: per, idEq: per / Math.PI, width: del >= 0 ? 2 * r + 2 * Rc * s : 2 * r - 2 * Rc * s };
}

// ---- + geometry-truth helpers
export const rotF = ([x, y], [cx, cy], a) => { const r = a * Math.PI / 180, c = Math.cos(r), s = Math.sin(r);
  return [cx + (x - cx) * c - (y - cy) * s, cy + (x - cx) * s + (y - cy) * c]; };
export const tipRise = (alpha) => Math.hypot(...rotF(GEO.TIP1, GEO.HUB, alpha)) - GEO.R_ROOT;  // 0.43@1.30, 1.25@3.746, 1.43@4.28, 1.66@4.97
export const tabBump = (u) => Math.max(0, Math.min(u, U_DETENT, U_ON - u));                    // tab rides 0.4 out of the V notches
export const tabLocal = (u) => [67.80 + tabBump(u), -2.70 - u];                                  // pawl-local (α = 0)
// truth §2.3 spring centreline at u = 0 (truth-geometry.json spring_centreline_u0): tab, lower leg, fold, upper leg, U-detent, flange
const SPRING_U0 = [[67.8, -2.7], [68.2, -2.3], [68.2, 14.3], [68.2, 14.3], [68.239, 14.547], [68.353, 14.77], [68.53, 14.947], [68.753, 15.061],
  [69, 15.1], [72.75, 15.1], [72.75, 15.1], [72.997, 15.061], [73.22, 14.947], [73.397, 14.77], [73.511, 14.547], [73.55, 14.3], [73.55, -3.95],
  [70.15, -3.95], [70.15, -6.45], [73.55, -6.45], [73.55, -14.9], [69.6, -14.9]];
export function springCentreline(u, alpha) {
  // every y − u; the lower leg replaced by a cubic from the fold corner c0 (tangent −y) to the tab (tangent into the notch)
  const c0 = [68.20, 14.30 - u], t = rotF(tabLocal(u), GEO.HUB, alpha);
  const L = Math.hypot(c0[0] - t[0], c0[1] - t[1]) / 3, d = Math.SQRT1_2;
  const p1 = [c0[0], c0[1] - L], p2 = [t[0] + L * d, t[1] + L * d];
  const out = [];
  for (let i = 0; i <= 28; i++) {
    const s = 1 - i / 28, a = (1 - s) ** 3, b = 3 * (1 - s) ** 2 * s, c = 3 * (1 - s) * s * s, e = s ** 3;
    out.push([a * c0[0] + b * p1[0] + c * p2[0] + e * t[0], a * c0[1] + b * p1[1] + c * p2[1] + e * t[1]]);
  }
  for (let i = 4; i < SPRING_U0.length; i++) out.push([SPRING_U0[i][0], SPRING_U0[i][1] - u]);
  return out;                                                                                    // tab first, flange last
}

// ---- state
export function create() {
  return { theta: THETA_OPEN, alpha: 0, u: 0, notch: 0, peak: 0, hold: 0, dTheta: 0,
           key: { at: "stand", depth: 0, kappa: 0, pinY: PIN.yEnter },     // + 'stand' | 'air' | 'keyhole' | 'slot'
           shim: { phi: SHIM.parkPhi, under: false },                       // + phi is never null; park = −50
           events: [] };
}
const moveToward = (x, t, d) => (Math.abs(t - x) <= d ? t : x + Math.sign(t - x) * d);
const crossedUp = (a, b, at) => a < at && b >= at;
const crossedDown = (a, b, at) => a > at && b <= at;

// ---- one physics step. want = { jaw?: θ*, key?: { at?, depth?, kappa?, pinY? }, shim?: φ* }
export function step(s, want = {}, dt) {
  const ev = [];
  const was = { theta: s.theta, alpha: s.alpha, u: s.u, kappa: s.key.kappa, pinY: s.key.pinY, under: s.shim.under, phi: s.shim.phi, hold: s.hold };
  // + transport: the page moves the key between stations (keyPose); the model refuses it unless κ is back at 0
  if (want.key) {
    const still = Math.abs(s.key.kappa) <= 0.5;
    if (want.key.at !== undefined && want.key.at !== s.key.at && still) { s.key.at = want.key.at; s.key.kappa = 0; if (s.key.at !== "slot") s.key.pinY = PIN.yEnter; }
    if (want.key.depth !== undefined && want.key.depth !== s.key.depth && still) s.key.depth = want.key.depth;
  }
  const capKey = s.key.at === "keyhole" && s.key.depth >= 1;
  // 1. spring: the pin in the slot pushes it ON (the flag in turn 1 pushes it OFF, below)
  if (s.key.at === "slot") { s.key.pinY = Math.max(PIN.yEnd - 0.2, Math.min(PIN.yEnter, want.key?.pinY ?? s.key.pinY)); s.u = Math.max(s.u, Math.min(U_ON, PIN.yTouch - s.key.pinY)); }
  // 2. key turn, limited by the spring stop (turn 1) or by the pawl's lift limit (turn 2)
  let limited = false;
  if (capKey && want.key?.kappa !== undefined) {
    let k = moveToward(s.key.kappa, want.key.kappa, 240 * dt);
    if (k > 0) { if (uLimitTurn1(k) <= 0 && s.u <= 0.02) k = Math.min(k, KEY.endTurn1); s.u = Math.min(s.u, Math.max(0, uLimitTurn1(k))); if (k >= KEY.endTurn1) k = KEY.endTurn1; }
    if (k < 0) { const lim = alphaLimit(s.u); let lo = k; while (alphaKey(lo) > lim && lo < 0) lo += 0.05; limited = lo > k + 1e-9; k = lo; }
    if (s.key.kappa <= 0 && k > 0) s.key.uStart = s.u;                                   // + turn 1 begins: was there anything to release?
    s.key.kappa = k;
  }
  // 3. pawl lift demanded by key and shim
  const aKey = capKey && s.key.kappa < 0 ? alphaKey(s.key.kappa) : 0;
  const aShim = s.shim.under ? ALPHA_SHIM : 0;
  // 4. jaw: closing needs the pawl to cam up; opening is blocked by the square faces unless the pawl is clear
  s.peak = 0;
  if (want.jaw !== undefined) {
    let th = moveToward(s.theta, want.jaw, 90 * dt);
    const lim = alphaLimit(s.u);
    for (let t = Math.min(s.theta, th); t <= Math.max(s.theta, th); t += 0.01) s.peak = Math.max(s.peak, alphaJaw(t));
    if (th > s.theta) {
      for (let t = s.theta; t <= th; t += 0.02) if (Math.max(alphaJaw(t), aKey, aShim) > lim && alphaJaw(t) > Math.max(aKey, aShim)) {
        th = Math.max(s.theta, t - 0.02); ev.push({ type: "blocked", why: notchAt(s.theta) === 0 ? "closing" : "double lock" }); break; }
    } else if (th < s.theta) {
      // + notch 0 (the lead-in, before the first click) is free too: the draft pushed the jaw forward to θ1 there
      const free = Math.max(aKey, aShim) >= ALPHA_CLEAR || s.theta <= THETA_FREE_OPEN || notchAt(s.theta) === 0 || s.theta > thetaOf(NPOS) + 0.01;
      if (!free) { const floor = thetaOf(Math.max(1, notchAt(s.theta))); if (th < floor) { th = floor; ev.push({ type: "blocked", why: "teeth" }); } }
    }
    const n0 = notchAt(s.theta), n1 = notchAt(th);
    if (n1 > n0 && th > s.theta && Math.max(aKey, aShim) < ALPHA_CLEAR) ev.push({ type: "click", n: n1 });
    s.theta = th;
  }
  s.notch = notchAt(s.theta);
  s.dTheta = s.theta - was.theta;
  // 5. shim: lies on the tooth tips; passes the pawl's toothed end only while a click holds the pawl tips on the tips
  if (want.shim !== undefined) {
    let p = moveToward(s.shim.phi, want.shim, SHIM.rate * dt);
    if (!s.shim.under && p > SHIM.blockedPhi) {
      if (s.peak >= ALPHA_TIPS - 0.05 && alphaLimit(s.u) >= ALPHA_SHIM) { s.shim.under = true; ev.push({ type: "shim", what: "under" }); }
      else { p = SHIM.blockedPhi; if (was.phi < SHIM.blockedPhi - 1e-6) ev.push({ type: "shim", what: "blocked" }); }
    }
    if (s.shim.under && p < SHIM.blockedPhi - 0.01) { s.shim.under = false; ev.push({ type: "shim", what: "out" }); }
    if (crossedUp(was.phi, p, SHIM.mouthPhi)) ev.push({ type: "shim", what: "mouth" });
    s.shim.phi = p;
  }
  if (Math.abs(s.shim.phi - SHIM.blockedPhi) < 1e-6 && !s.shim.under && ev.some((e) => e.type === "blocked" && e.why === "double lock")) ev.push({ type: "shim", what: "jammed" });
  // 6. pawl lift
  s.hold = Math.max(aKey, s.shim.under ? ALPHA_SHIM : 0);
  s.alpha = Math.min(Math.max(alphaJaw(s.theta), s.hold), Math.max(alphaLimit(s.u), alphaJaw(s.theta)));
  // + 7. events
  if (crossedUp(was.u, s.u + 1e-9, U_ON)) ev.push({ type: "dl", on: true });
  if (crossedDown(was.u, s.u, U_RELEASED)) ev.push({ type: "dl", on: false });
  if (crossedUp(was.kappa, s.key.kappa, KEY.touchFlange) && was.u > 0) ev.push({ type: "touch", what: "flange" });
  if (crossedDown(was.kappa, s.key.kappa, KEY.touchShoulder)) ev.push({ type: "touch", what: "shoulder" });
  if (s.key.at === "slot" && crossedDown(was.pinY, s.key.pinY, PIN.yTouch)) ev.push({ type: "touch", what: "fold" });
  if (crossedUp(was.kappa, s.key.kappa + 1e-9, KEY.endTurn1)) ev.push({ type: "stop", turn: 1, idle: (s.key.uStart ?? 0) <= 0.02 });
  if (limited && was.kappa > s.key.kappa + 1e-6) ev.push(s.u > U_RELEASED ? { type: "stall", at: s.key.kappa } : { type: "stop", turn: 2 });
  if (aKey >= ALPHA_CLEAR && crossedUp(was.alpha, s.alpha, ALPHA_CLEAR)) ev.push({ type: "clear" });
  if (crossedUp(was.theta, s.theta, THETA_MOUTH)) ev.push({ type: "mouth", dir: "in" });
  if (crossedDown(was.theta, s.theta, THETA_MOUTH)) ev.push({ type: "mouth", dir: "out" });
  if (was.hold >= ALPHA_CLEAR && s.hold < ALPHA_CLEAR && s.notch > 0 && s.theta > THETA_FREE_OPEN) ev.push({ type: "relock", n: s.notch });
  if (was.alpha > 0.5 && s.alpha <= 0.05 && !ev.some((e) => e.type === "click")) ev.push({ type: "drop", to: s.notch === 0 || s.theta <= THETA_FREE_OPEN ? "stud" : "root" });
  // + every event carries the key angle and the pawl lift of the sub-step it fired in: a frame may run several sub-steps,
  // and the words must name the stop, not where the key has moved on to by the frame's end (S3 gate)
  for (const e of ev) { if (e.kappa === undefined) e.kappa = s.key.kappa; if (e.alpha === undefined) e.alpha = s.alpha; }
  s.events = ev;
  return s;
}

// ---- + derived words
export function classify(s) {
  if (s.shim.under && s.notch > 0) return "SHIMMED";
  if (s.notch > 0 && s.hold >= ALPHA_CLEAR) return "RELEASED";
  if (s.notch === 0) return s.theta > THETA_MOUTH ? "ENTERING" : s.u >= 3.9 ? "DOUBLE_OPEN" : "OPEN";
  if (s.key.at === "keyhole" && s.key.depth >= 1) return "KEYED";
  return s.u >= 3.9 ? "DOUBLE" : "LOCKED";
}
const mm = (n) => Math.round(loopAt(thetaOf(n)).perimeter);
const up = (alpha) => tipRise(alpha).toFixed(1);
// readout (≤ 36 chars) for the state, plus `event` when this step's events produce a string the page should hold ≥ 0.6 s;
// status (aria-live phase, '' when unchanged) and valuetext (written only when it changes)
export function say(s, events = s.events, prev = {}) {
  const phase = classify(s), n = s.notch, kap = Math.round(Math.abs(s.key.kappa)), turn = s.key.kappa > 0 ? 1 : 2;
  let event = "";
  for (const e of events) {
    if (e.type === "click") event = n >= NPOS && s.theta > thetaOf(NPOS) + 0.01 ? "swing-through · strand passes free" : `click · position ${e.n} of ${NPOS}`;
    else if (e.type === "blocked" && e.why === "teeth") event = s.key.kappa <= KEY.touchShoulder && s.key.kappa > KEY.teethClear ? "pull blocked · teeth not clear yet" : "pull blocked · square faces meet";
    else if (e.type === "blocked" && e.why === "closing") event = "closing blocked · double lock on";
    else if (e.type === "blocked" && e.why === "double lock") event = `squeeze stops · pawl up ${up(e.alpha ?? s.alpha)} of 1.2`;
    else if (e.type === "shim") event = { mouth: "shim in · 8 mm along the teeth", blocked: "shim stops at the pawl's teeth", under: "squeeze · shim slips under", out: "shim out · pawl back on its stud", jammed: `shim jammed · pawl up ${up(e.alpha ?? s.alpha)} of 1.2` }[e.what];
    else if (e.type === "dl") event = e.on ? "detent parked 0.6 mm over pawl" : `turn 1 · ${Math.round(KEY.dlReleased)}° · double lock off`;
    else if (e.type === "touch") event = { flange: `turn 1 · ${Math.round(KEY.touchFlange)}° · flag meets spring`, shoulder: `turn 2 · ${Math.round(-KEY.touchShoulder)}° · flag meets pawl`, fold: "" }[e.what];   // the fold touch: no held string (the slide's words follow at once; "pin in the slot" is the state's)
    else if (e.type === "stop") event = e.turn === 1 ? `turn 1 · ${Math.round(KEY.endTurn1)}° · ${e.idle ? "nothing to release" : "stop"}` : `turn 2 · ${Math.round(Math.abs(e.kappa ?? s.key.kappa))}° · stop, teeth up ${up(e.alpha ?? s.alpha)}`;
    else if (e.type === "stall") event = `turn 2 stalls · ${Math.round(Math.abs(e.kappa ?? s.key.kappa))}° · up ${up(e.alpha ?? s.alpha)} of 1.2`;
    else if (e.type === "clear") event = `turn 2 · ${Math.round(-KEY.teethClear)}° · teeth clear`;
    else if (e.type === "mouth") event = e.dir === "in" ? "closing · nose inside the case" : "open · strand clear of the case";
    else if (e.type === "relock") event = `pawl dropped · locked at ${e.n} of ${NPOS}`;
  }
  let readout;
  const keyIn = s.key.at === "keyhole" && s.key.depth >= 1;
  if (s.key.at === "slot" && s.u >= 0.05 && s.u < U_ON) readout = `double-locking · slid ${s.u.toFixed(1)} of 4 mm`;
  else if (s.key.at === "slot" && s.u < 0.05) readout = "pin in the slot";
  // + the strand swinging out under the lifted pawl is the beat, even with the key held at the turn-2 stop (U A19)
  else if (keyIn && s.key.kappa < -0.5 && s.dTheta < 0 && s.hold >= ALPHA_CLEAR && s.theta > THETA_MOUTH) readout = "opening · teeth pass under pawl";
  else if (keyIn && s.key.kappa >= KEY.endTurn1 - 0.01) readout = `turn 1 · ${Math.round(KEY.endTurn1)}° · ${(s.key.uStart ?? 0) <= 0.02 ? "nothing to release" : "stop"}`;
  else if (keyIn && s.key.kappa > 0.5) readout = s.key.kappa < KEY.touchFlange || s.u <= 0 ? `turn 1 · ${kap}° · flag swings free` : `turn 1 · ${kap}° · pushed ${(U_ON - s.u).toFixed(1)} of 4 mm`;
  else if (keyIn && s.key.kappa < -0.5) readout = s.key.kappa > KEY.touchShoulder ? `turn 2 · ${kap}° · flag swings free` : s.alpha >= ALPHA_CLEAR ? `turn 2 · ${kap}° · teeth up ${up(s.alpha)}` : `turn 2 · ${kap}° · teeth up ${up(s.alpha)} of 1.2`;
  else if (phase === "SHIMMED") readout = "shimmed · strand pulls free";
  else if (phase === "RELEASED") readout = s.dTheta < 0 ? "opening · teeth pass under pawl" : `turn 2 · ${kap}° · teeth clear`;
  else if (phase === "ENTERING") readout = tipRise(s.alpha) >= 0.05 ? `closing · pawl riding up ${up(s.alpha)} mm` : s.dTheta < 0 ? "opening · strand leaving the case" : "closing · nose inside the case";
  // design A: a strand parked part way out (θ −60, −75) is not called open; "open" is the swing out to the bumper (θ −100)
  else if (phase === "OPEN" || phase === "DOUBLE_OPEN") readout = s.dTheta > 0 ? "closing · nose at the mouth" : keyIn ? "open · strand clear of the case" : s.theta > THETA_OPEN + 5 ? "strand out of the case" : s.key.at === "stand" ? "open · key parked" : "open";
  else if (n >= NPOS && s.theta > thetaOf(NPOS) + 0.01) readout = "swing-through · strand passes free";
  else if (s.dTheta > 0 && tipRise(s.alpha) >= 0.05) readout = `closing · pawl riding up ${up(s.alpha)} mm`;
  else if (phase === "DOUBLE") readout = `double-locked · ${n} of ${NPOS} · ${mm(n)} mm`;
  else if (phase === "KEYED") readout = s.u > U_RELEASED ? "key in · turn toward the swivel" : `locked · ${n} of ${NPOS} · inside ${mm(n)} mm`;
  else readout = `locked · ${n} of ${NPOS} · inside ${mm(n)} mm`;
  const words = {
    OPEN: "open", ENTERING: "closing", DOUBLE_OPEN: "open, double lock set", RELEASED: "released, pawl lifted clear", SHIMMED: "shimmed, pawl held up",
    LOCKED: `locked at position ${n} of ${NPOS}, inside ${mm(Math.max(1, n))} millimetres`, DOUBLE: `double-locked at position ${n} of ${NPOS}`,
    KEYED: s.u >= 3.9 ? `key in, double-locked at position ${n} of ${NPOS}` : `key in, locked at position ${n} of ${NPOS}`,
  };
  const valuetext = words[phase];
  const statusOf = { OPEN: "open", DOUBLE_OPEN: "open", LOCKED: `locked at position ${n} of ${NPOS}`, DOUBLE: "double-locked", RELEASED: "teeth clear", SHIMMED: "shimmed open" };
  const status = statusOf[phase] && statusOf[phase] !== prev.status ? statusOf[phase] : "";
  return { readout, event, phase, valuetext: valuetext !== prev.valuetext ? valuetext : "", status };
}

// ---- + truth-drift guard, run by every build (throws on failure) and by `node model.mjs --check`
export function check() {
  const near = (a, b, e, what) => { if (!(Math.abs(a - b) <= e)) throw new Error(`model check: ${what} ${a} vs ${b}`); };
  const truth = (c, what) => { if (!c) throw new Error(`model check: ${what}`); };
  near(loopAt(thetaOf(1)).perimeter, 213.4, 0.2, "P(θ1)"); near(loopAt(thetaOf(23)).perimeter, 147.3, 0.2, "P(θ23)");
  near(loopAt(thetaOf(9)).perimeter, 189.0, 0.2, "P(θ9)"); near(loopAt(thetaOf(23)).width, 45.4, 0.2, "W(θ23)");
  near(alphaKey(KEY.teethClear), ALPHA_CLEAR, 0.02, "clear"); near(alphaKey(KEY.endOff), ALPHA_MAX_OFF, 0.06, "end off");
  near(alphaKey(KEY.stallOn), alphaLimit(4), 0.03, "stall"); near(alphaKey(KEY.tipsOnTips), ALPHA_TIPS, 0.03, "tips");
  near(uLimitTurn1(KEY.dlReleased), U_RELEASED, 0.03, "release"); near(uLimitTurn1(KEY.endTurn1), 0, 0.03, "end 1");
  near(uLimitTurn1(KEY.touchFlange), 4, 0.06, "touch"); near(alphaLimit(0), ALPHA_MAX_OFF, 0.01, "ALIM 0");
  near(alphaLimit(4), ALPHA_MAX_ON, 0.01, "ALIM 4"); near(tipRise(1.30), 0.43, 0.01, "rise on"); near(tipRise(4.97), 1.66, 0.01, "rise off");
  // replay of scratch/truth/test-model.mjs (without the reference solver)
  const s = create(), dt = 1 / 60;
  const run = (want, secs) => { const seen = []; for (let i = 0; i < secs * 60; i++) { step(s, want, dt); seen.push(...s.events); } return seen; };
  let seen = run({ jaw: thetaOf(9) }, 3);
  near(s.theta, thetaOf(9), 1e-6, "close to 9"); truth(seen.filter((e) => e.type === "click").length === 9, "nine clicks");
  seen = run({ jaw: thetaOf(9) - 10 }, 1);
  near(s.theta, thetaOf(9), 1e-6, "pull blocked"); truth(seen.some((e) => e.type === "blocked" && e.why === "teeth"), "pull blocked event");
  s.key.at = "slot"; s.key.pinY = PIN.yEnter; seen = run({ key: { pinY: 12.1 } }, 1);
  near(s.u, U_ON, 1e-9, "pin ON"); truth(seen.some((e) => e.type === "dl" && e.on), "dl on event"); s.key.at = "stand";
  seen = run({ jaw: thetaOf(10) }, 1);
  near(s.theta - thetaOf(9), 0.92, 0.05, "squeeze blocked"); truth(seen.some((e) => e.type === "blocked" && e.why === "double lock"), "squeeze event");
  seen = run({ shim: SHIM.underPhi }, 3);
  near(s.shim.phi, SHIM.blockedPhi, 1e-9, "shim stopped"); truth(!s.shim.under, "shim jammed");
  run({ shim: SHIM.parkPhi }, 3); near(s.shim.phi, SHIM.parkPhi, 1e-9, "shim parked");
  step(s, { key: { at: "keyhole", depth: 1 } }, dt);
  seen = run({ key: { kappa: -120 } }, 1);
  near(s.key.kappa, KEY.stallOn, 0.1, "turn 2 stalls"); truth(seen.some((e) => e.type === "stall"), "stall event");
  run({ key: { kappa: 0 } }, 1);
  seen = run({ key: { kappa: 230 } }, 2);
  near(s.key.kappa, KEY.endTurn1, 1e-9, "turn 1 stop"); near(s.u, 0, 0.03, "turn 1 releases"); truth(seen.some((e) => e.type === "dl" && !e.on), "dl off event");
  run({ key: { kappa: 0 } }, 2);
  seen = run({ key: { kappa: -120 } }, 1);
  near(s.key.kappa, KEY.endOff, 0.2, "turn 2 stop (u 0.02 after turn 1 stops it at -85.95)"); truth(s.alpha >= ALPHA_CLEAR, "teeth clear"); truth(seen.some((e) => e.type === "clear"), "clear event");
  run({ jaw: THETA_OPEN, key: { kappa: -120 } }, 2);
  near(s.theta, THETA_OPEN, 1e-9, "pull open"); truth(s.notch === 0, "open");
  run({ key: { kappa: 0 } }, 1); step(s, { key: { at: "stand", depth: 0 } }, dt);
  truth(s.alpha === 0 && s.key.at === "stand", "key back");
  run({ jaw: thetaOf(9) }, 3); near(s.theta, thetaOf(9), 1e-6, "close again");
  run({ shim: SHIM.underPhi }, 3); near(s.shim.phi, SHIM.blockedPhi, 1e-9, "shim at the teeth"); truth(!s.shim.under, "shim blocked single-locked");
  seen = run({ jaw: thetaOf(10), shim: SHIM.underPhi }, 1);
  truth(s.shim.under && s.notch === 10, "shim under after one squeeze"); near(s.alpha, ALPHA_SHIM, 1e-9, "shim holds");
  run({ jaw: THETA_OPEN, shim: SHIM.underPhi }, 2);
  near(s.theta, THETA_OPEN, 1e-9, "pull open over the shim");
  return true;
}

